class Produk {
  int? id;
  String? title;
  String? description;
  String? category;
  double? price;
  double? discountPercentage;
  double? rating;
  int? stock;
  String? thumbnail;

  Produk({
    this.id,
    this.title,
    this.description,
    this.category,
    this.price,
    this.discountPercentage,
    this.rating,
    this.stock,
    this.thumbnail,
  });

  Produk.fromJson(Map<dynamic, dynamic> json) {
    id = json['id'] as int?;
    title = json['title'];
    description = json['description'];
    category = json['category'];
    price = json['price'];
    discountPercentage = json['discountPercentage'];
    rating = json['rating'];
    stock = json['stock'];
    thumbnail = json['thumbnail'];
  }
}
